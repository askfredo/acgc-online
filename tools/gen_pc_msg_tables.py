#!/usr/bin/env python3
"""Generate pc/src/pc_msg_tables.c (the game's character map and message control codes)
from msg_tool.py, for the PC port's own dialogue text (pc/src/pc_msg.c).

    tools/gen_pc_msg_tables.py > pc/src/pc_msg_tables.c
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import msg_tool  # noqa: E402


def c_str(s):
    out = []
    after_hex = False
    for b in s.encode("utf-8"):
        if 0x20 <= b < 0x7F:
            # A hex escape would swallow a following hex digit: split the literal.
            if after_hex and chr(b) in "0123456789abcdefABCDEF":
                out.append('""')
            out.append("\\" + chr(b) if b in (0x22, 0x5C) else chr(b))
            after_hex = False
        else:
            out.append("\\x%02X" % b)
            after_hex = True
    return '"' + "".join(out) + '"'


def main():
    assert len(msg_tool.CHAR_MAP) == 256
    assert len(msg_tool.COMMANDS) == len(msg_tool.CONT_SIZES)
    print("/* pc_msg_tables.c - generated by tools/gen_pc_msg_tables.py from tools/msg_tool.py. Do not edit. */")
    print('#include "pc_msg.h"')
    print()
    print("/* UTF-8 text of each byte of the game's character set. */")
    print("const char* const pc_msg_char_map[256] = {")
    for i, ch in enumerate(msg_tool.CHAR_MAP):
        print("    %s, /* 0x%02X */" % (c_str(ch), i))
    print("};")
    print()
    print("/* Control codes (0x7F <code> <args>): name and total size in bytes. */")
    print("const PcMsgControl pc_msg_controls[] = {")
    for name, size in zip(msg_tool.COMMANDS, msg_tool.CONT_SIZES):
        print("    { %s, %d }," % (c_str(name) if name else "NULL", size))
    print("};")
    print("const int pc_msg_control_count = %d;" % len(msg_tool.COMMANDS))


if __name__ == "__main__":
    main()
